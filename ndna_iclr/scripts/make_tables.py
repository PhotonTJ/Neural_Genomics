"""Emit LaTeX tables from whatever results exist in results/.

Writes into tables/ as standalone .tex fragments that can be \\input directly. Each
table prints the source NPZ names in a comment so a number in the paper can be traced
back to the run that produced it.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config as C                       # noqa: E402
from core import harness                 # noqa: E402

BS = chr(92)
NL = BS + BS


def _w(name, lines, sources):
    path = os.path.join(C.TABLES, name)
    head = [f"% generated by scripts/make_tables.py",
            f"% sources: {', '.join(sources) if sources else 'none'}"]
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write("\n".join(head + lines) + "\n")
    print(f"  wrote {name}  ({len(sources)} source run(s))")


def dose_response():
    blocks = harness.load_all("exp01_dose_response")
    if not blocks:
        return
    src = [t for t, _, _ in blocks]
    rows = []
    for tag, a, man in blocks:
        mk = (man or {}).get("config", {}).get("model_key", tag)
        labels = [str(s) for s in a["labels"]]
        for i, lab in enumerate(labels):
            rows.append(f"{mk} & {lab} & {a['length_ratio'][i]:.3f} & "
                        f"{a['kappa_mean'][i]:.4f} & {a['belief_mean'][i]:.3f} & "
                        f"{a['perplexity'][i]:.2f} {NL}")
        rows.append(f"{BS}midrule")
    rho = [(t, float(a["rho_quant_length"]), float(a["rho_prune_length"]))
           for t, a, _ in blocks]
    note = "; ".join(f"{t.split('__')[1]}: $\\rho_q={q:.2f}$, $\\rho_p={p:.2f}$"
                     for t, q, p in rho)
    lines = [
        BS + "begin{table}[t]", BS + "centering" + BS + "small",
        BS + "caption{Dose--response under compression. Spearman $" + BS +
        "rho$ over per-seed observations: " + note + ".}",
        BS + "label{tab:dose}",
        BS + "begin{tabular}{llrrrr}", BS + "toprule",
        f"Model & Dose & $\\mathcal{{L}}/\\mathcal{{L}}_0$ & $\\bar{{\\kappa}}$ & "
        f"$\\lVert\\mathbf{{v}}\\rVert$ & PPL {NL}", BS + "midrule",
        *rows[:-1], BS + "bottomrule",
        BS + "end{tabular}", BS + "end{table}",
    ]
    _w("tab_dose_response.tex", lines, src)


def stability():
    blocks = harness.load_all("exp04_task_stability")
    if not blocks:
        return
    src, rows, pooled = [], [], []
    for tag, a, man in blocks:
        mk = (man or {}).get("config", {}).get("model_key", tag)
        v = np.asarray(a["task_pairs"], float)
        pooled.append(v)
        src.append(tag)
        rows.append(f"{mk} & {len(v)} & {v.min():.3f} & {np.median(v):.3f} & "
                    f"{v.mean():.3f} & {v.max():.3f} {NL}")
    P = np.concatenate(pooled) if pooled else np.array([])
    theta = float(np.quantile(P, 0.90)) if P.size else float("nan")
    lines = [
        BS + "begin{table}[t]", BS + "centering" + BS + "small",
        BS + "caption{Task-induced variation in the nDNA triad; the pooled upper decile "
        "fixes the acceptance threshold $" + BS + "theta$.}",
        BS + "label{tab:stability}",
        BS + "begin{tabular}{lrrrrr}", BS + "toprule",
        f"Model & pairs & min & median & mean & max {NL}", BS + "midrule",
        *rows, BS + "midrule",
        f"{BS}textbf{{Pooled}} & {len(P)} & {P.min():.3f} & {np.median(P):.3f} & "
        f"{P.mean():.3f} & {P.max():.3f} {NL}" if P.size else "",
        BS + "bottomrule", BS + "end{tabular}",
        BS + f"vspace{{1mm}}{BS}footnotesize $" + BS + f"theta := q_{{90}} = {theta:.3f}$.",
        BS + "end{table}",
    ]
    _w("tab_stability.tex", [l for l in lines if l], src)


def provenance():
    blocks = harness.load_all("exp10_provenance")
    if not blocks:
        return
    src, rows = [], []
    for tag, a, _ in blocks:
        src.append(tag)
        for i in range(len(a["query"])):
            q = str(a["query"][i]).split("/")[-1]
            rows.append(f"{BS}texttt{{{q}}} & {a['true_base'][i]} & {a['predicted'][i]} & "
                        f"{a['d_true'][i]:.3f} & {a['margin'][i]*100:.1f}" + BS + "% & "
                        f"{'yes' if a['top1'][i] else 'no'} {NL}")
        acc = float(a["top1_acc"]) * 100
        ch = float(a["chance"]) * 100
    lines = [
        BS + "begin{table}[t]", BS + "centering" + BS + "small",
        BS + "caption{Model provenance: nearest candidate base by DTW over the triad. "
        f"Top-1 accuracy {acc:.1f}" + BS + f"% against {ch:.1f}" + BS + "% chance.}}",
        BS + "label{tab:provenance}",
        BS + "begin{tabular}{lllrrl}", BS + "toprule",
        f"Query & True base & Predicted & $d$ & margin & hit {NL}", BS + "midrule",
        *rows, BS + "bottomrule", BS + "end{tabular}", BS + "end{table}",
    ]
    _w("tab_provenance.tex", lines, src)


def invariance():
    blocks = harness.load_all("exp05_invariance")
    if not blocks:
        return
    src, rows = [], []
    for tag, a, man in blocks:
        mk = (man or {}).get("config", {}).get("model_key", tag)
        src.append(tag)
        for i, c in enumerate(a["gain_scale"]):
            rows.append(f"{mk} & {c:.1f} & {a['max_logit_deviation'][i]:.2e} & "
                        f"{a['triad_length_ratio'][i]:.4f} & "
                        f"{a['hidden_raw_length_ratio'][i]:.4f} {NL}")
    lines = [
        BS + "begin{table}[t]", BS + "centering" + BS + "small",
        BS + "caption{Reparameterisation check. The triad is expected to be flat in $c$; "
        "the raw Euclidean hidden-state length is expected to scale with it.}",
        BS + "label{tab:invariance}",
        BS + "begin{tabular}{lrrrr}", BS + "toprule",
        f"Model & $c$ & $\\max|\\Delta$logit$|$ & triad $\\mathcal{{L}}$ ratio & "
        f"raw hidden ratio {NL}", BS + "midrule",
        *rows, BS + "bottomrule", BS + "end{tabular}", BS + "end{table}",
    ]
    _w("tab_invariance.tex", lines, src)


if __name__ == "__main__":
    print(f"reading {C.RESULTS}")
    for fn in (dose_response, stability, provenance, invariance):
        try:
            fn()
        except Exception as e:
            print(f"  skip {fn.__name__}: {e}")
    print(f"tables in {C.TABLES}")
